USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR IF NOT EXISTS GQH_MONITOR WITH CREDIT_QUOTA=5 FREQUENCY=DAILY START_TIMESTAMP=IMMEDIATELY TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND_IMMEDIATE;
CREATE WAREHOUSE IF NOT EXISTS GQH_WH WAREHOUSE_SIZE='XSMALL' AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE RESOURCE_MONITOR=GQH_MONITOR;
ALTER WAREHOUSE GQH_WH SET STATEMENT_TIMEOUT_IN_SECONDS=300;
CREATE DATABASE IF NOT EXISTS GQH;
CREATE SCHEMA IF NOT EXISTS GQH.RAW;
CREATE SCHEMA IF NOT EXISTS GQH.MARKET;
CREATE SCHEMA IF NOT EXISTS GQH.CONTEXT;
CREATE STAGE IF NOT EXISTS GQH.RAW.ASSETS ENCRYPTION=(TYPE='SNOWFLAKE_SSE');
CREATE FILE FORMAT IF NOT EXISTS GQH.RAW.PARQUET TYPE=PARQUET USE_LOGICAL_TYPE=TRUE;
CREATE TABLE IF NOT EXISTS GQH.RAW.FILES (COLLECTION VARCHAR, VERSION VARCHAR, SOURCE_PATH VARCHAR, SHA256 VARCHAR, BYTES NUMBER, STAGE_PATH VARCHAR, LOADED BOOLEAN DEFAULT FALSE, IMPORTED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS GQH.MARKET.OBSERVATIONS (DATA VARIANT, SOURCE_PATH VARCHAR, VERSION VARCHAR);
CREATE TABLE IF NOT EXISTS GQH.CONTEXT.PASSAGES (DOC_SHA VARCHAR, SOURCE_PATH VARCHAR, ORDINAL NUMBER, START_LINE NUMBER, END_LINE NUMBER, BODY VARCHAR) CHANGE_TRACKING=TRUE;
CREATE ROLE IF NOT EXISTS GQH_RESEARCHER;
CREATE ROLE IF NOT EXISTS GQH_PUBLISHER;
GRANT ROLE GQH_RESEARCHER TO ROLE GQH_PUBLISHER;
GRANT USAGE ON WAREHOUSE GQH_WH TO ROLE GQH_RESEARCHER;
GRANT USAGE ON DATABASE GQH TO ROLE GQH_RESEARCHER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE GQH TO ROLE GQH_RESEARCHER;
GRANT SELECT ON ALL TABLES IN DATABASE GQH TO ROLE GQH_RESEARCHER;
GRANT READ ON STAGE GQH.RAW.ASSETS TO ROLE GQH_RESEARCHER;
GRANT READ ON STAGE GQH.RAW.ASSETS TO ROLE GQH_PUBLISHER;
GRANT WRITE ON STAGE GQH.RAW.ASSETS TO ROLE GQH_PUBLISHER;
GRANT INSERT, UPDATE ON TABLE GQH.RAW.FILES TO ROLE GQH_PUBLISHER;
GRANT INSERT ON TABLE GQH.MARKET.OBSERVATIONS TO ROLE GQH_PUBLISHER;
GRANT INSERT ON TABLE GQH.CONTEXT.PASSAGES TO ROLE GQH_PUBLISHER;
